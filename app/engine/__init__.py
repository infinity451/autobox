"""自动化引擎包。

engine（引擎）是 AutoBox 的心脏，负责“规则是怎么被触发、怎么执行”的所有逻辑：
- rules.py     规则管理：增删改查数据库里的规则
- matcher.py   条件匹配：判断一个文件/事件满不满足规则的条件
- actions.py   动作执行：执行“移动/复制/重命名/通知”等动作
- triggers.py  触发器：盯文件变化、定时器，一有动静就通知引擎
- scheduler.py 引擎主控：把上面几块串起来，处理触发、匹配、执行、记日志

这个 __init__.py 同样是“包身份证”，让 engine 文件夹能被 import。
"""

